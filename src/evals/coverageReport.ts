import { buildAdversarialPromptPack } from "./releaseArtifacts";
import type { Scenario, ScenarioDomain, Sensitivity } from "../shared/types";

export interface CoverageBucket {
  id: string;
  count: number;
  percentage: number;
}

export interface ScenarioCoverageReport {
  benchmark: string;
  version: string;
  generatedAt: string;
  scenarioCount: number;
  domainCoverage: CoverageBucket[];
  sensitivityCoverage: CoverageBucket[];
  architectureLayerCoverage: CoverageBucket[];
  externalInteractionCount: number;
  boundaryCrossingRequiredCount: number;
  adversarialVariantCount: number;
  heldOutVariantPlan: Array<{
    split: "seed" | "development" | "held_out";
    scenarioIds: string[];
  }>;
  limitations: string[];
}

function percentage(count: number, total: number): number {
  return Number(((count / Math.max(1, total)) * 100).toFixed(1));
}

function countBuckets<T extends string>(values: T[], allValues: T[]): CoverageBucket[] {
  return allValues.map((id) => {
    const count = values.filter((value) => value === id).length;
    return { id, count, percentage: percentage(count, values.length) };
  });
}

function deterministicSplit(scenarios: Scenario[]): ScenarioCoverageReport["heldOutVariantPlan"] {
  const sorted = [...scenarios].sort((a, b) => a.id.localeCompare(b.id));

  return [
    {
      split: "seed",
      scenarioIds: sorted.filter((_, index) => index % 5 === 0).map((scenario) => scenario.id)
    },
    {
      split: "development",
      scenarioIds: sorted.filter((_, index) => index % 5 >= 1 && index % 5 <= 3).map((scenario) => scenario.id)
    },
    {
      split: "held_out",
      scenarioIds: sorted.filter((_, index) => index % 5 === 4).map((scenario) => scenario.id)
    }
  ];
}

export function buildScenarioCoverageReport(scenarios: Scenario[]): ScenarioCoverageReport {
  const domains: ScenarioDomain[] = [
    "knowledge_work",
    "finance_like_planning",
    "health_like_sensitive",
    "education",
    "customer_agent_negotiation",
    "household_admin",
    "career"
  ];
  const sensitivities: Sensitivity[] = ["public", "personal", "confidential", "sensitive", "regulated"];
  const layers = ["local", "personal_cloud", "federated"];
  const allDataItems = scenarios.flatMap((scenario) => scenario.dataItems);

  return {
    benchmark: "personal-ai-sovereignty-benchmark",
    version: "0.5.0-coverage",
    generatedAt: new Date("2026-05-22T00:00:00.000Z").toISOString(),
    scenarioCount: scenarios.length,
    domainCoverage: countBuckets(
      scenarios.map((scenario) => scenario.domain),
      domains
    ),
    sensitivityCoverage: countBuckets(
      allDataItems.map((item) => item.sensitivity),
      sensitivities
    ),
    architectureLayerCoverage: layers.map((layer) => {
      const count = scenarios.filter((scenario) =>
        scenario.architectureLayerFocus.includes(layer as never)
      ).length;
      return { id: layer, count, percentage: percentage(count, scenarios.length) };
    }),
    externalInteractionCount: scenarios.filter((scenario) => scenario.externalInteraction).length,
    boundaryCrossingRequiredCount: scenarios.filter(
      (scenario) => scenario.requiresBoundaryCrossingForSuccess
    ).length,
    adversarialVariantCount: buildAdversarialPromptPack(scenarios).variantCount,
    heldOutVariantPlan: deterministicSplit(scenarios),
    limitations: [
      "Coverage buckets describe authored synthetic fixtures, not naturally sampled user tasks.",
      "The held-out split is deterministic scaffolding for future benchmark governance; it is not a secret split in this public repo.",
      "Scenario coverage does not imply measurement validity without human annotations and stronger system baselines."
    ]
  };
}

export function renderScenarioCoverageMarkdown(report: ScenarioCoverageReport): string {
  return `# Scenario Coverage Report

Generated by \`pnpm eval\`.

## Summary

- Scenario count: ${report.scenarioCount}
- External-interaction scenarios: ${report.externalInteractionCount}
- Boundary-crossing-required scenarios: ${report.boundaryCrossingRequiredCount}
- Adversarial prompt variants: ${report.adversarialVariantCount}

## Domain Coverage

| Domain | Count | Share |
| --- | ---: | ---: |
${report.domainCoverage
  .map((bucket) => `| ${bucket.id} | ${bucket.count} | ${bucket.percentage}% |`)
  .join("\n")}

## Sensitivity Coverage

| Sensitivity | Count | Share |
| --- | ---: | ---: |
${report.sensitivityCoverage
  .map((bucket) => `| ${bucket.id} | ${bucket.count} | ${bucket.percentage}% |`)
  .join("\n")}

## Architecture Layer Coverage

| Layer | Scenario Count | Share |
| --- | ---: | ---: |
${report.architectureLayerCoverage
  .map((bucket) => `| ${bucket.id} | ${bucket.count} | ${bucket.percentage}% |`)
  .join("\n")}

## Public Split Plan

${report.heldOutVariantPlan
  .map((split) => `- ${split.split}: ${split.scenarioIds.length} scenarios`)
  .join("\n")}

## Limitations

${report.limitations.map((limitation) => `- ${limitation}`).join("\n")}
`;
}
