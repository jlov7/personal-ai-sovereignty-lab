import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { getScenarioById, scenarios } from "../scenarios/library";
import {
  createFailedModelPlan,
  createOracleModelPlan,
  createUnsafeCentralizedModelPlan,
  evaluateModelPlanTranscript
} from "../models/transcriptPlans";
import { localHttpConfigsFromEnv, runLocalHttpModelPlan } from "../models/localHttpAdapter";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const outputDir = resolve(root, "outputs");

interface ScenarioTranscriptEvaluation {
  scenarioId: string;
  evaluations: Array<{
    plan: {
      modelName: string;
      rawText: string;
    };
    evaluation: {
      passed: boolean;
      score: number;
      findings: Array<{
        id: string;
        passed: boolean;
        severity: string;
        evidence: string;
        expectation: string;
      }>;
    };
  }>;
}

function renderTranscriptReport(
  scenarioEvaluations: ScenarioTranscriptEvaluation[],
  localModelStatus: string
): string {
  const flattened = scenarioEvaluations.flatMap((scenario) =>
    scenario.evaluations.map((entry) => ({
      scenarioId: scenario.scenarioId,
      modelName: entry.plan.modelName,
      passed: entry.evaluation.passed,
      score: entry.evaluation.score,
      failures: entry.evaluation.findings.filter((finding) => !finding.passed)
    }))
  );
  const modelNames = [...new Set(flattened.map((row) => row.modelName))];
  const summaryRows = modelNames.map((modelName) => {
    const entries = flattened.filter((row) => row.modelName === modelName);
    const passes = entries.filter((row) => row.passed).length;
    const averageScore =
      entries.reduce((sum, row) => sum + row.score, 0) / Math.max(1, entries.length);
    return `| ${modelName} | ${passes}/${entries.length} | ${averageScore.toFixed(1)} |`;
  });
  const rows = scenarioEvaluations.flatMap((scenario) =>
    scenario.evaluations.map((entry) => {
      const failures = entry.evaluation.findings
        .filter((finding) => !finding.passed)
        .map((finding) => finding.id)
        .join("<br>");
      return `| ${scenario.scenarioId} | ${entry.plan.modelName} | ${entry.evaluation.score} | ${
        entry.evaluation.passed ? "pass" : "fail"
      } | ${failures || "none"} |`;
    })
  );

  const notableFailures = scenarioEvaluations.flatMap((scenario) =>
    scenario.evaluations.flatMap((entry) =>
      entry.evaluation.findings
        .filter((finding) => !finding.passed)
        .map(
          (finding) =>
            `- ${scenario.scenarioId} / ${entry.plan.modelName} / ${finding.id}: ${finding.evidence} Expected: ${finding.expectation}`
        )
    )
  );

  return `# Model Transcript Evaluation

Generated by \`pnpm model:eval\`.

## Summary

- Local model status: ${localModelStatus}
- Scenario count: ${scenarioEvaluations.length}
- Evaluation count: ${scenarioEvaluations.reduce((sum, scenario) => sum + scenario.evaluations.length, 0)}

## Model Summary

| Model | Pass Rate | Average Score |
| --- | ---: | ---: |
${summaryRows.join("\n")}

## Scores

| Scenario | Model | Score | Result | Failed Findings |
| --- | --- | ---: | --- | --- |
${rows.join("\n")}

## Notable Findings

${notableFailures.length > 0 ? notableFailures.join("\n") : "- No failed findings."}

## Interpretation

This report evaluates generated model plans against the deterministic policy oracle. Passing means the plan satisfied the current boundary, consent, raw-release, and explicit-block checks for the selected scenarios. It does not prove broader model safety.
`;
}

async function main(): Promise<void> {
  await mkdir(outputDir, { recursive: true });

  const scenarioIds = (process.env.PAISL_MODEL_SCENARIO_IDS ?? process.env.PAISL_MODEL_SCENARIO_ID ?? "subscription-negotiation")
    .split(",")
    .map((id) => id.trim())
    .filter(Boolean);
  const selectedScenarios =
    scenarioIds.length === 1 && scenarioIds[0] === "all"
      ? scenarios
      : scenarioIds.map((id) => getScenarioById(id));
  const localConfigs = localHttpConfigsFromEnv(process.env);
  const outputStem = process.env.PAISL_MODEL_OUTPUT_STEM ?? "model_transcript_eval";

  let localModelStatus =
    "skipped: set PAISL_MODEL_BASE_URL and PAISL_MODEL_NAME or PAISL_MODEL_NAMES to run local OpenAI-compatible models.";
  const scenarioEvaluations = [];

  for (const scenario of selectedScenarios) {
    const oraclePlan = createOracleModelPlan(scenario);
    const unsafePlan = createUnsafeCentralizedModelPlan(scenario);
    const plans = [oraclePlan, unsafePlan];

    for (const localConfig of localConfigs) {
      try {
        const localPlan = await runLocalHttpModelPlan(scenario, localConfig);
        plans.push(localPlan);
      } catch (error) {
        plans.push(createFailedModelPlan(scenario, localConfig.model, error));
      }
      localModelStatus = `ran: ${localConfigs.map((config) => config.model).join(", ")} at ${
        localConfig.baseUrl
      }`;
    }

    scenarioEvaluations.push({
      scenarioId: scenario.id,
      evaluations: plans.map((plan) => ({
        plan,
        evaluation: evaluateModelPlanTranscript(scenario, plan)
      }))
    });
  }

  await writeFile(
    resolve(outputDir, `${outputStem}.json`),
    `${JSON.stringify(
      {
        generatedAt: new Date("2026-05-22T00:00:00.000Z").toISOString(),
        scenarioIds: selectedScenarios.map((scenario) => scenario.id),
        localModelStatus,
        scenarioEvaluations
      },
      null,
      2
    )}\n`
  );

  await writeFile(
    resolve(outputDir, `${outputStem}.md`),
    renderTranscriptReport(scenarioEvaluations, localModelStatus)
  );
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
