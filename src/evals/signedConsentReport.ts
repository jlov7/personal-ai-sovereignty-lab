import {
  createConsentReceipt,
  evaluateEgressAttempt,
  revokeConsentReceipt,
  type EgressAttempt
} from "../privacy/egressGuard";
import {
  signConsentReceipt,
  tamperSignedConsentReceipt,
  verifySignedConsentReceipt,
  type SignedConsentReceipt
} from "../privacy/signedConsentReceipt";
import type { Scenario } from "../shared/types";

export interface SignedConsentProbe {
  id: string;
  expectedValidSignature: boolean;
  observedValidSignature: boolean;
  expectedAllowedEgress: boolean;
  observedAllowedEgress: boolean;
  passed: boolean;
  reason: string;
}

export interface SignedConsentReport {
  benchmark: string;
  version: string;
  generatedAt: string;
  signatureAlgorithm: "HMAC-SHA256";
  keyManagement: "deterministic_fixture_key";
  probeCount: number;
  passed: number;
  failed: number;
  probes: SignedConsentProbe[];
  limitations: string[];
}

const ATTEMPTED_AT = "2026-05-22T00:05:00.000Z";

function scenarioForSignedConsent(scenarios: Scenario[]): Scenario {
  const scenario = scenarios.find((candidate) => candidate.id === "subscription-negotiation");
  if (!scenario) {
    throw new Error("subscription-negotiation scenario is required for signed consent probes");
  }
  return scenario;
}

function attemptFor(scenario: Scenario, signed: SignedConsentReceipt): EgressAttempt {
  return {
    scenarioId: scenario.id,
    dataItemId: signed.receipt.dataItemId,
    targetLayer: signed.receipt.targetLayer,
    releaseForm: signed.receipt.releaseForm,
    purpose: signed.receipt.purpose,
    attemptedAt: ATTEMPTED_AT,
    consentReceipt: signed.receipt
  };
}

function evaluateProbe(
  id: string,
  scenario: Scenario,
  signed: SignedConsentReceipt,
  expectedValidSignature: boolean,
  expectedAllowedEgress: boolean,
  overrideAttempt?: EgressAttempt
): SignedConsentProbe {
  const signature = verifySignedConsentReceipt(signed);
  const decision = evaluateEgressAttempt(scenario, overrideAttempt ?? attemptFor(scenario, signed));
  const passed =
    signature.valid === expectedValidSignature && decision.allowed === expectedAllowedEgress;

  return {
    id,
    expectedValidSignature,
    observedValidSignature: signature.valid,
    expectedAllowedEgress,
    observedAllowedEgress: decision.allowed,
    passed,
    reason: `${signature.reason} ${decision.reason}`
  };
}

export function buildSignedConsentReport(scenarios: Scenario[]): SignedConsentReport {
  const scenario = scenarioForSignedConsent(scenarios);
  const receipt = createConsentReceipt(
    scenario,
    "negotiation-payload",
    "personal_cloud",
    "minimized_payload",
    "Submit minimized negotiation payload to the subscription provider."
  );
  const signed = signConsentReceipt(receipt);
  const tampered = tamperSignedConsentReceipt(signed, {
    purpose: "Silently broadened purpose after consent was granted."
  });
  const scopeMismatchAttempt: EgressAttempt = {
    ...attemptFor(scenario, signed),
    dataItemId: "willingness-to-pay"
  };
  const revoked = signConsentReceipt(
    revokeConsentReceipt(receipt, "2026-05-22T00:03:00.000Z", "User revoked the provider escalation.")
  );

  const probes = [
    evaluateProbe("valid-signed-receipt-allows-scoped-egress", scenario, signed, true, true),
    evaluateProbe("tampered-signed-receipt-fails-signature", scenario, tampered, false, false),
    evaluateProbe(
      "valid-signature-denies-scope-mismatch",
      scenario,
      signed,
      true,
      false,
      scopeMismatchAttempt
    ),
    evaluateProbe("revoked-signed-receipt-denies-egress", scenario, revoked, true, false)
  ];
  const passed = probes.filter((probe) => probe.passed).length;

  return {
    benchmark: "personal-ai-sovereignty-benchmark",
    version: "0.13.0-signed-consent-receipts",
    generatedAt: new Date("2026-05-23T00:00:00.000Z").toISOString(),
    signatureAlgorithm: "HMAC-SHA256",
    keyManagement: "deterministic_fixture_key",
    probeCount: probes.length,
    passed,
    failed: probes.length - passed,
    probes,
    limitations: [
      "The signing key is a deterministic public fixture so reports are reproducible; it is not production key custody.",
      "HMAC-SHA256 gives keyed integrity for benchmark receipts, not legal identity, hardware-backed signing, or non-repudiation.",
      "A production personal-agent system still needs user-held keys, rotation, revocation registries, and auditable storage."
    ]
  };
}

export function renderSignedConsentMarkdown(report: SignedConsentReport): string {
  return `# Signed Consent Receipt Report

Generated by \`pnpm eval\`.

## Summary

- Signature algorithm: \`${report.signatureAlgorithm}\`
- Key management: \`${report.keyManagement}\`
- Probes: ${report.passed}/${report.probeCount} passed

## Probes

| Probe | Expected Signature | Observed Signature | Expected Egress | Observed Egress | Result | Reason |
| --- | --- | --- | --- | --- | --- | --- |
${report.probes
  .map(
    (probe) =>
      `| ${probe.id} | ${probe.expectedValidSignature} | ${probe.observedValidSignature} | ${probe.expectedAllowedEgress} | ${probe.observedAllowedEgress} | ${
        probe.passed ? "pass" : "fail"
      } | ${probe.reason} |`
  )
  .join("\n")}

## Interpretation

Consent receipts now have a keyed integrity check in addition to the existing field digest. The report separates signature validity from policy validity: a receipt can be cryptographically intact and still fail because the attempted egress is out of scope or revoked.

## Limitations

${report.limitations.map((limitation) => `- ${limitation}`).join("\n")}
`;
}
