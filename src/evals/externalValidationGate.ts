import type { AggregateEmpiricalAttackReport } from "./aggregateEmpiricalAttackReport";
import type { AnnotationAgreementReport } from "./annotationAgreement";
import type { BaselineSubmissionReport } from "./baselineSubmission";

export interface ExternalValidationGateCheck {
  id: string;
  result: "pass" | "partial" | "blocked_external";
  evidence: string;
  interpretation: string;
}

export interface ExternalValidationGateReport {
  benchmark: string;
  version: string;
  generatedAt: string;
  status: "blocked_external" | "candidate_ready";
  checks: ExternalValidationGateCheck[];
  nextEvidenceRequired: string[];
  limitations: string[];
}

export function buildExternalValidationGateReport(
  annotationAgreementReport: AnnotationAgreementReport,
  baselineSubmissionReport: BaselineSubmissionReport,
  aggregateEmpiricalAttackReport: AggregateEmpiricalAttackReport
): ExternalValidationGateReport {
  const checks: ExternalValidationGateCheck[] = [
    {
      id: "annotation-files-present",
      result: annotationAgreementReport.annotationCount > 0 ? "partial" : "blocked_external",
      evidence: `${annotationAgreementReport.annotationCount} annotation files`,
      interpretation: "The annotation pipeline has input files, but seed files are not validation."
    },
    {
      id: "annotation-overlap",
      result:
        annotationAgreementReport.status === "computed" ? "pass" : "blocked_external",
      evidence: `${annotationAgreementReport.overlappingCaseCount}/${annotationAgreementReport.minimumOverlappingCaseCount} overlapping cases`,
      interpretation: "Human-label validity needs enough overlapping cases to compute agreement."
    },
    {
      id: "independent-baseline-submissions",
      result:
        baselineSubmissionReport.externalSubmissionCount > 0 ? "pass" : "blocked_external",
      evidence: `${baselineSubmissionReport.externalSubmissionCount} independent external submissions`,
      interpretation: "At least one non-author baseline must submit trace-bearing evidence."
    },
    {
      id: "production-agent-baseline",
      result:
        baselineSubmissionReport.productionSubmissionCount > 0 ? "pass" : "blocked_external",
      evidence: `${baselineSubmissionReport.productionSubmissionCount} production personal-agent submissions`,
      interpretation: "A benchmark about personal agents needs at least one production-grade personal-agent run."
    },
    {
      id: "aggregate-attack-candidates",
      result:
        aggregateEmpiricalAttackReport.needsEmpiricalMitigationCount > 0 ? "partial" : "blocked_external",
      evidence: `${aggregateEmpiricalAttackReport.needsEmpiricalMitigationCount} synthetic cohort cases need empirical mitigation`,
      interpretation: "Synthetic attacks identify candidates for real aggregate linkage or differencing experiments."
    }
  ];
  const candidateReady = checks.every((check) => check.result === "pass");

  return {
    benchmark: "personal-ai-sovereignty-benchmark",
    version: "0.9.0-external-validation-gate",
    generatedAt: new Date("2026-05-23T00:00:00.000Z").toISOString(),
    status: candidateReady ? "candidate_ready" : "blocked_external",
    checks,
    nextEvidenceRequired: [
      "Collect at least three independent annotators across at least five overlapping cases.",
      "Accept at least one independent trace-bearing baseline submission.",
      "Evaluate at least one production-grade personal-agent or tool-using agent implementation.",
      "Run a real aggregate linkage, differencing, or reconstruction attack against representative aggregate fixtures."
    ],
    limitations: [
      "This gate is a release-readiness diagnostic; it cannot certify annotator independence by itself.",
      "The gate intentionally remains blocked when only seed fixtures are present.",
      "Passing this gate would make the benchmark validation-ready, not automatically validated."
    ]
  };
}

export function renderExternalValidationGateMarkdown(report: ExternalValidationGateReport): string {
  return `# External Validation Gate

Generated by \`pnpm eval\`.

## Status

- Status: \`${report.status}\`

## Checks

| Check | Result | Evidence | Interpretation |
| --- | --- | --- | --- |
${report.checks
  .map((check) => `| ${check.id} | ${check.result} | ${check.evidence} | ${check.interpretation} |`)
  .join("\n")}

## Next Evidence Required

${report.nextEvidenceRequired.map((item) => `- ${item}`).join("\n")}

## Limitations

${report.limitations.map((limitation) => `- ${limitation}`).join("\n")}
`;
}
