import { evaluateAggregateRisks, type AggregateRiskProbe } from "../privacy/aggregateRisk";
import type { Scenario } from "../shared/types";

export interface AggregateRiskReport {
  benchmark: string;
  version: string;
  generatedAt: string;
  scenarioCount: number;
  probeCount: number;
  allowCount: number;
  requireControlCount: number;
  blockCount: number;
  averageRiskScore: number;
  probes: AggregateRiskProbe[];
  limitations: string[];
}

export function buildAggregateRiskReport(scenarios: Scenario[]): AggregateRiskReport {
  const probes = evaluateAggregateRisks(scenarios);
  const averageRiskScore =
    probes.reduce((sum, probe) => sum + probe.reconstructionRiskScore, 0) /
    Math.max(1, probes.length);

  return {
    benchmark: "personal-ai-sovereignty-benchmark",
    version: "0.5.0-aggregate-risk-scaffold",
    generatedAt: new Date("2026-05-22T00:00:00.000Z").toISOString(),
    scenarioCount: scenarios.length,
    probeCount: probes.length,
    allowCount: probes.filter((probe) => probe.recommendedDecision === "allow_aggregate").length,
    requireControlCount: probes.filter(
      (probe) => probe.recommendedDecision === "require_dp_or_larger_cohort"
    ).length,
    blockCount: probes.filter((probe) => probe.recommendedDecision === "block_aggregate").length,
    averageRiskScore: Math.round(averageRiskScore * 10) / 10,
    probes,
    limitations: [
      "This is a synthetic linkability stress test, not a formal privacy proof.",
      "Cohort sizes are deterministic fixtures derived from scenario metadata, not sampled populations.",
      "A real benchmark needs empirical linkage attacks and differential privacy accounting before aggregate-release claims."
    ]
  };
}

export function renderAggregateRiskMarkdown(report: AggregateRiskReport): string {
  const decisionRows = [
    ["allow_aggregate", report.allowCount],
    ["require_dp_or_larger_cohort", report.requireControlCount],
    ["block_aggregate", report.blockCount]
  ]
    .map(([decision, count]) => `| ${decision} | ${count} |`)
    .join("\n");
  const topRiskRows = [...report.probes]
    .sort((a, b) => b.reconstructionRiskScore - a.reconstructionRiskScore)
    .slice(0, 20)
    .map(
      (probe) =>
        `| ${probe.scenarioId} | ${probe.dataItemId} | ${probe.reconstructionRiskScore} | ${probe.syntheticCohortSize} | ${probe.kAnonymityEstimate} | ${probe.recommendedDecision} | ${probe.linkabilityFactors.join(", ") || "none"} |`
    )
    .join("\n");

  return `# Aggregate Reconstruction Risk Report

Generated by \`pnpm eval\`.

## Summary

- Scenario count: ${report.scenarioCount}
- Probe count: ${report.probeCount}
- Average synthetic reconstruction-risk score: ${report.averageRiskScore}/100

## Recommended Decisions

| Decision | Count |
| --- | ---: |
${decisionRows}

## Highest-Risk Probes

| Scenario | Data Item | Risk Score | Synthetic Cohort | k Estimate | Decision | Linkability Factors |
| --- | --- | ---: | ---: | ---: | --- | --- |
${topRiskRows}

## Interpretation

The benchmark now has an explicit aggregate-risk gate: safe aggregate labels are not trusted by name alone. Any aggregate candidate with small synthetic cohorts, regulated/sensitive context, PII, or federated release surface is forced into stronger controls or blocked.

## Limitations

${report.limitations.map((limitation) => `- ${limitation}`).join("\n")}
`;
}
