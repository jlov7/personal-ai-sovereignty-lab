import {
  runProcessEgressGuard,
  type ProcessEgressAuditEvent,
  type ProcessEgressProbe
} from "../privacy/processEgressGuard";

export interface ProcessEgressGuardReport {
  benchmark: string;
  version: string;
  generatedAt: string;
  enforcementLayer: "process_preload";
  guardedApis: string[];
  childExitCode: number | null;
  auditEventCount: number;
  probeCount: number;
  passed: number;
  failed: number;
  probes: ProcessEgressProbe[];
  auditEvents: ProcessEgressAuditEvent[];
  limitations: string[];
}

export async function buildProcessEgressGuardReport(): Promise<ProcessEgressGuardReport> {
  const run = await runProcessEgressGuard();
  const passed = run.probes.filter((probe) => probe.passed).length;

  return {
    benchmark: "personal-ai-sovereignty-benchmark",
    version: "0.12.0-process-egress-guard",
    generatedAt: new Date("2026-05-23T00:00:00.000Z").toISOString(),
    enforcementLayer: "process_preload",
    guardedApis: [
      "globalThis.fetch",
      "node:http.request",
      "node:http.get",
      "node:https.request",
      "node:https.get",
      "node:net.connect",
      "node:net.createConnection",
      "node:tls.connect"
    ],
    childExitCode: run.childExitCode,
    auditEventCount: run.auditEvents.length,
    probeCount: run.probes.length,
    passed,
    failed: run.probes.length - passed,
    probes: run.probes,
    auditEvents: run.auditEvents,
    limitations: [
      "This is process-level preload instrumentation for Node runtimes, not a kernel firewall or macOS sandbox profile.",
      "The guard blocks common Node egress primitives before untrusted benchmark code executes, but code can bypass it if it can spawn an unguarded process or load native networking outside the preload policy.",
      "Allowed fetch calls return synthetic responses during pnpm eval so the benchmark remains offline and reproducible."
    ]
  };
}

export function renderProcessEgressGuardMarkdown(report: ProcessEgressGuardReport): string {
  return `# Process-Level Egress Guard Report

Generated by \`pnpm eval\`.

## Summary

- Enforcement layer: \`${report.enforcementLayer}\`
- Guarded APIs: ${report.guardedApis.length}
- Child exit code: ${report.childExitCode}
- Audit events: ${report.auditEventCount}
- Probes: ${report.passed}/${report.probeCount} passed

## Probes

| Probe | API | Expected Allowed | Observed Allowed | Result | Reason |
| --- | --- | --- | --- | --- | --- |
${report.probes
  .map(
    (probe) =>
      `| ${probe.id} | ${probe.api} | ${probe.expectedAllowed} | ${probe.observedAllowed} | ${
        probe.passed ? "pass" : "fail"
      } | ${probe.reason} |`
  )
  .join("\n")}

## Audit Events

| API | Host | Allowed | Reason |
| --- | --- | --- | --- |
${report.auditEvents
  .map((event) => `| ${event.api} | ${event.host} | ${event.allowed} | ${event.reason} |`)
  .join("\n")}

## Interpretation

The benchmark now includes a process-level runtime experiment: untrusted child code is started with a preload guard before it can import network modules. The guard traps Fetch, HTTP, HTTPS, raw TCP, and TLS primitives and writes an audit event for each attempted egress. This is meaningfully stronger than application-level fetch mediation, but it is still not an OS or kernel boundary.

## Limitations

${report.limitations.map((limitation) => `- ${limitation}`).join("\n")}
`;
}
