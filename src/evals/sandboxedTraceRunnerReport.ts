import {
  runSandboxedTrace,
  verifySandboxedExecutionAttestation,
  type SandboxedExecutionAttestation
} from "../broker/sandboxedTraceRunner";
import type { ExternalAgentTrace } from "./externalTraceEvaluator";

export interface SandboxedTraceRunnerReport {
  benchmark: string;
  version: string;
  generatedAt: string;
  runnerMode: "node_child_process_preload_guard";
  sourcePaths: string[];
  traceCount: number;
  signedExecutionAttestationCount: number;
  verifiedExecutionAttestationCount: number;
  passedExecutionAttestationCount: number;
  brokerExecutedActionCount: number;
  childExecutedActionCount: number;
  brokerBlockedActionCount: number;
  skippedByBrokerCount: number;
  escapeAttemptCount: number;
  guardDeniedEscapeCount: number;
  guardAuditEventCount: number;
  attestations: SandboxedExecutionAttestation[];
  limitations: string[];
}

export async function buildSandboxedTraceRunnerReport(
  traces: ExternalAgentTrace[],
  sourcePaths: string[]
): Promise<SandboxedTraceRunnerReport> {
  const attestations = await Promise.all(traces.map((trace) => runSandboxedTrace(trace)));
  const verifiedExecutionAttestationCount = attestations.filter(
    (attestation) => verifySandboxedExecutionAttestation(attestation).valid
  ).length;

  return {
    benchmark: "personal-ai-sovereignty-benchmark",
    version: "0.16.0-sandboxed-trace-runner",
    generatedAt: new Date("2026-05-23T00:00:00.000Z").toISOString(),
    runnerMode: "node_child_process_preload_guard",
    sourcePaths,
    traceCount: traces.length,
    signedExecutionAttestationCount: attestations.length,
    verifiedExecutionAttestationCount,
    passedExecutionAttestationCount: attestations.filter((attestation) => attestation.passed).length,
    brokerExecutedActionCount: attestations.reduce(
      (sum, attestation) => sum + attestation.brokerExecutedActionCount,
      0
    ),
    childExecutedActionCount: attestations.reduce(
      (sum, attestation) => sum + attestation.childExecutedActionCount,
      0
    ),
    brokerBlockedActionCount: attestations.reduce(
      (sum, attestation) => sum + attestation.brokerBlockedActionCount,
      0
    ),
    skippedByBrokerCount: attestations.reduce(
      (sum, attestation) => sum + attestation.skippedByBrokerCount,
      0
    ),
    escapeAttemptCount: attestations.reduce(
      (sum, attestation) => sum + attestation.escapeAttemptCount,
      0
    ),
    guardDeniedEscapeCount: attestations.reduce(
      (sum, attestation) => sum + attestation.guardDeniedEscapeCount,
      0
    ),
    guardAuditEventCount: attestations.reduce(
      (sum, attestation) => sum + attestation.guardAuditEventCount,
      0
    ),
    attestations,
    limitations: [
      "The runner executes broker-approved trace actions in a guarded Node child process, not a production sandbox.",
      "The preload guard denies the probed untrusted Fetch and raw-socket escape paths, but it is bypassable outside this runner profile.",
      "Execution attestations use deterministic fixture signatures for reproducibility, not identity-bound non-repudiation.",
      "The report is stronger than replay-only broker attestations but still not independent external validation."
    ]
  };
}

export function renderSandboxedTraceRunnerMarkdown(report: SandboxedTraceRunnerReport): string {
  return `# Sandboxed Trace Runner Report

Generated by \`pnpm eval\`.

## Summary

- Runner mode: \`${report.runnerMode}\`
- Trace count: ${report.traceCount}
- Signed execution attestations: ${report.signedExecutionAttestationCount}
- Verified execution attestations: ${report.verifiedExecutionAttestationCount}
- Passed execution attestations: ${report.passedExecutionAttestationCount}
- Broker-approved actions: ${report.brokerExecutedActionCount}
- Child-executed actions: ${report.childExecutedActionCount}
- Broker-blocked actions: ${report.brokerBlockedActionCount}
- Skipped by broker: ${report.skippedByBrokerCount}
- Escape attempts: ${report.escapeAttemptCount}
- Escape attempts denied by guard: ${report.guardDeniedEscapeCount}
- Guard audit events: ${report.guardAuditEventCount}

## Execution Attestations

| Trace | Broker Attestation | Child Exit | Broker Executed | Child Executed | Skipped By Broker | Escape Denials | Signature | Result |
| --- | --- | ---: | ---: | ---: | ---: | ---: | --- | --- |
${report.attestations
  .map(
    (attestation) =>
      `| ${attestation.traceId} | ${attestation.brokerAttestationId} | ${
        attestation.childExitCode ?? "null"
      } | ${attestation.brokerExecutedActionCount} | ${attestation.childExecutedActionCount} | ${
        attestation.skippedByBrokerCount
      } | ${attestation.guardDeniedEscapeCount}/${attestation.escapeAttemptCount} | ${
        verifySandboxedExecutionAttestation(attestation).valid ? "valid" : "invalid"
      } | ${attestation.passed ? "pass" : "fail"} |`
  )
  .join("\n")}

## Action Execution Details

${report.attestations
  .map(
    (attestation) => `### ${attestation.traceId}

| Action | Broker Decision | Attempted In Child | Observed | Target Host | API | Error | Result |
| --- | --- | --- | --- | --- | --- | --- | --- |
${attestation.actionExecutions
  .map(
    (execution) =>
      `| ${execution.actionId} | ${execution.brokerDecision} | ${execution.attemptedInChild} | ${
        execution.observedStatus
      } | ${execution.targetHost} | ${execution.api ?? "none"} | ${execution.errorCode ?? "none"} | ${
        execution.passed ? "pass" : "fail"
      } |`
  )
  .join("\n")}

| Escape Attempt | API | Target Host | Observed Denied | Error | Result |
| --- | --- | --- | --- | --- | --- |
${attestation.escapeAttempts
  .map(
    (attempt) =>
      `| ${attempt.id} | ${attempt.api} | ${attempt.targetHost} | ${attempt.observedDenied} | ${
        attempt.errorCode ?? "none"
      } | ${attempt.passed ? "pass" : "fail"} |`
  )
  .join("\n")}
`
  )
  .join("\n")}

## Interpretation

Broker replay says what the benchmark policy would allow. The sandboxed runner adds an execution-shaped check: broker-approved actions run in a child process with a preload egress guard, broker-blocked actions are skipped before child execution, and direct escape attempts are denied by the guard. This is a stronger local artifact than replay-only attestations, but it is still not production sandboxing or independent validation.

## Limitations

${report.limitations.map((limitation) => `- ${limitation}`).join("\n")}
`;
}
