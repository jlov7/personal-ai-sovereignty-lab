import {
  brokerExternalTrace,
  verifyBrokerAttestation,
  type BrokeredTraceAttestation
} from "../broker/traceBroker";
import {
  evaluateExternalTrace,
  type ExternalAgentTrace,
  type ExternalTraceEvaluation
} from "./externalTraceEvaluator";

export interface BrokerAttestationEvaluationLink {
  traceId: string;
  externalTraceScore: number;
  privacyBoundaryViolations: number;
  consentViolations: number;
  aggregateControlViolations: number;
  brokerExecutedActions: number;
  brokerBlockedActions: number;
  claimedCompletedButBlocked: number;
  attestationValid: boolean;
}

export interface BrokerAttestationReport {
  benchmark: string;
  version: string;
  generatedAt: string;
  brokerMode: "deterministic_policy_broker";
  sourcePaths: string[];
  traceCount: number;
  signedAttestationCount: number;
  verifiedAttestationCount: number;
  actionCount: number;
  brokerExecutedActionCount: number;
  brokerBlockedActionCount: number;
  claimedCompletedButBlockedCount: number;
  submittedBlockedConfirmedCount: number;
  evaluationLinks: BrokerAttestationEvaluationLink[];
  attestations: BrokeredTraceAttestation[];
  limitations: string[];
}

function linkFor(
  evaluation: ExternalTraceEvaluation,
  attestation: BrokeredTraceAttestation
): BrokerAttestationEvaluationLink {
  const verification = verifyBrokerAttestation(attestation);
  return {
    traceId: attestation.traceId,
    externalTraceScore: evaluation.totalScore,
    privacyBoundaryViolations: evaluation.privacyBoundaryViolations,
    consentViolations: evaluation.consentViolations,
    aggregateControlViolations: evaluation.aggregateControlViolations,
    brokerExecutedActions: attestation.executedActionCount,
    brokerBlockedActions: attestation.blockedActionCount,
    claimedCompletedButBlocked: attestation.claimedCompletedButBlockedCount,
    attestationValid: verification.valid
  };
}

export function buildBrokerAttestationReport(
  traces: ExternalAgentTrace[],
  sourcePaths: string[]
): BrokerAttestationReport {
  const attestations = traces.map((trace) => brokerExternalTrace(trace));
  const evaluations = traces.map((trace) => evaluateExternalTrace(trace));
  const evaluationLinks = attestations.map((attestation, index) =>
    linkFor(evaluations[index], attestation)
  );
  const verifiedAttestationCount = evaluationLinks.filter((link) => link.attestationValid).length;

  return {
    benchmark: "personal-ai-sovereignty-benchmark",
    version: "0.15.0-broker-attestations",
    generatedAt: new Date("2026-05-23T00:00:00.000Z").toISOString(),
    brokerMode: "deterministic_policy_broker",
    sourcePaths,
    traceCount: traces.length,
    signedAttestationCount: attestations.length,
    verifiedAttestationCount,
    actionCount: attestations.reduce((sum, attestation) => sum + attestation.submittedActionCount, 0),
    brokerExecutedActionCount: attestations.reduce(
      (sum, attestation) => sum + attestation.executedActionCount,
      0
    ),
    brokerBlockedActionCount: attestations.reduce(
      (sum, attestation) => sum + attestation.blockedActionCount,
      0
    ),
    claimedCompletedButBlockedCount: attestations.reduce(
      (sum, attestation) => sum + attestation.claimedCompletedButBlockedCount,
      0
    ),
    submittedBlockedConfirmedCount: attestations.reduce(
      (sum, attestation) => sum + attestation.submittedBlockedConfirmedCount,
      0
    ),
    evaluationLinks,
    attestations,
    limitations: [
      "Broker attestations are deterministic local benchmark evidence, not production broker execution.",
      "The attestation signature uses a public fixture key so reports are reproducible; it is not production key custody or non-repudiation.",
      "The confinement profile references the existing process, macOS, and Docker probes; pnpm eval does not run arbitrary third-party code inside those profiles.",
      "Independent systems must still submit traces and artifacts before this becomes external validation."
    ]
  };
}

export function renderBrokerAttestationMarkdown(report: BrokerAttestationReport): string {
  return `# Broker Attestation Report

Generated by \`pnpm eval\`.

## Summary

- Broker mode: \`${report.brokerMode}\`
- Trace count: ${report.traceCount}
- Signed attestations: ${report.signedAttestationCount}
- Verified attestations: ${report.verifiedAttestationCount}
- Submitted actions: ${report.actionCount}
- Broker executed actions: ${report.brokerExecutedActionCount}
- Broker blocked actions: ${report.brokerBlockedActionCount}
- Completed claims blocked by broker: ${report.claimedCompletedButBlockedCount}
- Submitted blocks confirmed: ${report.submittedBlockedConfirmedCount}

## Evaluator Links

| Trace | External Trace Score | Privacy Violations | Consent Violations | Aggregate Controls | Broker Executed | Broker Blocked | Completed Claims Blocked | Attestation |
| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |
${report.evaluationLinks
  .map(
    (link) =>
      `| ${link.traceId} | ${link.externalTraceScore} | ${link.privacyBoundaryViolations} | ${link.consentViolations} | ${link.aggregateControlViolations} | ${link.brokerExecutedActions} | ${link.brokerBlockedActions} | ${link.claimedCompletedButBlocked} | ${
        link.attestationValid ? "valid" : "invalid"
      } |`
  )
  .join("\n")}

## Action Results

${report.attestations
  .map(
    (attestation) => `### ${attestation.traceId}

- Attestation: \`${attestation.attestationId}\`
- Signature key: \`${attestation.signature.keyId}\`
- Signature valid: ${verifyBrokerAttestation(attestation).valid}
- Confinement profile: \`${attestation.confinementProfile}\`

| Action | Submitted | Broker Decision | Executed | Target Host | Findings |
| --- | --- | --- | --- | --- | --- |
${attestation.actionResults
  .map(
    (result) =>
      `| ${result.actionId} | ${result.submittedStatus} | ${result.brokerDecision} | ${
        result.brokerExecuted
      } | ${result.targetHost} | ${result.findings.map((finding) => `${finding.id}:${finding.severity}`).join("<br>")} |`
  )
  .join("\n")}
`
  )
  .join("\n")}

## Interpretation

The external trace evaluator is post-hoc: it scores what a submitted system claims it did. Broker attestations add a stricter local evidence layer: submitted actions are replayed against the benchmark's policy and egress rules, and the resulting execution/block decisions are signed. This is still not a production broker, but it closes the gap where a high-scoring trace could be only an unexecuted claim.

## Limitations

${report.limitations.map((limitation) => `- ${limitation}`).join("\n")}
`;
}
