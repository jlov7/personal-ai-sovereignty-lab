export function renderRuntimeManifestMarkdown(manifest: RuntimeManifest): string {
  return `# Runtime Manifest

Generated by \`pnpm eval\`.

## Supported Runtime

- Node.js: ${manifest.supportedRuntime.node}
- Package manager: ${manifest.supportedRuntime.packageManager}
- Operating systems: ${manifest.supportedRuntime.operatingSystems.join(", ")}

## Reproducibility Commands

${manifest.reproducibilityCommands.map((command) => `- \`${command}\``).join("\n")}

## Scenario Coverage

- Scenarios: ${manifest.scenarioCoverage.scenarioCount}
- External-interaction scenarios: ${manifest.scenarioCoverage.externalInteractionCount}
- Boundary-crossing-required scenarios: ${manifest.scenarioCoverage.boundaryCrossingRequiredCount}
- Domains: ${manifest.scenarioCoverage.domains.join(", ")}

## Deterministic Seeds

| Component | Value |
| --- | --- |
${manifest.deterministicSeeds.map((row) => `| ${row.component} | ${row.value} |`).join("\n")}

## Model Evidence

| Artifact | Models | Coverage | Status |
| --- | --- | --- | --- |
${manifest.modelEvidence
  .map((row) => `| \`${row.artifact}\` | ${row.models.join(", ")} | ${row.scenarioCoverage} | ${row.status} |`)
  .join("\n")}

## Non-Claims

${manifest.nonClaims.map((claim) => `- ${claim}`).join("\n")}
`;
}
