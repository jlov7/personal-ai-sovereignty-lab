import type { Scenario } from "../shared/types";

export interface RuntimeManifest {
  benchmark: string;
  version: string;
  generatedAt: string;
  supportedRuntime: {
    node: string;
    packageManager: string;
    operatingSystems: string[];
  };
  reproducibilityCommands: string[];
  deterministicSeeds: Array<{
    component: string;
    value: string;
  }>;
  modelEvidence: Array<{
    artifact: string;
    models: string[];
    scenarioCoverage: string;
    status: string;
  }>;
  scenarioCoverage: {
    scenarioCount: number;
    externalInteractionCount: number;
    boundaryCrossingRequiredCount: number;
    domains: string[];
  };
  nonClaims: string[];
}

