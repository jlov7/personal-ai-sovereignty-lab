import { buildAttackScripts, type AttackScript, type AttackTier } from "../adversary/scripts";
import { replayAttackScript } from "../adversary/replay";
import type { Scenario } from "../core/types";

export interface AttackScriptReport {
  benchmark: "personal-ai-sovereignty-harness";
  version: "0.21.0";
  generatedAt: string;
  scriptCount: number;
  tierCounts: Record<AttackTier, number>;
  familyCounts: Record<string, number>;
  replayControls: {
    scriptCount: number;
    compliantResisted: number;
    naiveFailed: number;
    passed: boolean;
  };
  scripts: AttackScript[];
  limitations: string[];
}

function increment(map: Record<string, number>, key: string): void {
  map[key] = (map[key] ?? 0) + 1;
}

export async function buildAttackScriptReport(scenarios: Scenario[]): Promise<AttackScriptReport> {
  const scripts = buildAttackScripts(scenarios);
  const scenarioById = new Map(scenarios.map((scenario) => [scenario.id, scenario]));
  const tierCounts: Record<AttackTier, number> = { T2: 0, T3: 0, T4: 0 };
  const familyCounts: Record<string, number> = {};
  let compliantResisted = 0;
  let naiveFailed = 0;

  for (const script of scripts) {
    const scenario = scenarioById.get(script.scenarioId);
    if (!scenario) {
      throw new Error(`Attack script ${script.id} refers to missing scenario ${script.scenarioId}.`);
    }
    tierCounts[script.tier] += 1;
    increment(familyCounts, script.family);
    const replay = await replayAttackScript(script, scenario);
    compliantResisted += replay.compliantResisted ? 1 : 0;
    naiveFailed += replay.naiveFailed ? 1 : 0;
  }

  return {
    benchmark: "personal-ai-sovereignty-harness",
    version: "0.21.0",
    generatedAt: new Date("2026-06-11T00:00:00.000Z").toISOString(),
    scriptCount: scripts.length,
    tierCounts,
    familyCounts,
    replayControls: {
      scriptCount: scripts.length,
      compliantResisted,
      naiveFailed,
      passed: compliantResisted === scripts.length && naiveFailed === scripts.length
    },
    scripts,
    limitations: [
      "Scripts are deterministic fixtures, not adaptive model-generated attacks.",
      "Replay controls prove fixture separation between compliant and naive agents; they do not calibrate difficulty against strong live models.",
      "The model-driven adaptive attacker is intentionally deferred until deterministic scripts are stable."
    ]
  };
}

export function renderAttackScriptReportMarkdown(report: AttackScriptReport): string {
  const tierRows = (Object.entries(report.tierCounts) as Array<[AttackTier, number]>)
    .map(([tier, count]) => `| ${tier} | ${count} |`)
    .join("\n");
  const familyRows = Object.entries(report.familyCounts)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([family, count]) => `| ${family} | ${count} |`)
    .join("\n");

  return `# Attack Script Report

Generated by \`pnpm eval\`.

## Summary

- Script count: ${report.scriptCount}
- Replay controls: ${report.replayControls.passed ? "pass" : "fail"}
- Compliant fixture resisted: ${report.replayControls.compliantResisted}/${report.replayControls.scriptCount}
- Naive fixture failed: ${report.replayControls.naiveFailed}/${report.replayControls.scriptCount}

## Tier Counts

| Tier | Scripts |
| --- | ---: |
${tierRows}

## Family Counts

| Family | Scripts |
| --- | ---: |
${familyRows}

## Interpretation

T1 remains the existing single-shot adversarial prompt pack. This report adds deterministic T2 multi-turn escalation, T3 indirect-injection, and T4 stateful/cross-run pressure scripts for harness replay. A stronger live-model calibration report is separate platform-tagged evidence and is not generated by the hermetic gate.

## Limitations

${report.limitations.map((limitation) => `- ${limitation}`).join("\n")}
`;
}
