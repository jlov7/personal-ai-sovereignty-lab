import { createHash } from "node:crypto";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { relative, resolve } from "node:path";

export interface ArtifactManifestEntry {
  path: string;
  sha256: string;
  bytes: number;
}

export interface ArtifactManifest {
  benchmark: string;
  version: string;
  generatedAt: string;
  artifactCount: number;
  entries: ArtifactManifestEntry[];
  verificationCommand: string;
}

const includedRoots = [
  ".devcontainer",
  ".dockerignore",
  ".github",
  "README.md",
  "CHANGELOG.md",
  "CITATION.cff",
  "CONTRIBUTING.md",
  "Dockerfile",
  "SECURITY.md",
  "docs",
  "examples",
  "huggingface",
  "outputs",
  "schemas",
  "src",
  "tests",
  "package.json",
  "pnpm-lock.yaml",
  "pnpm-workspace.yaml",
  "tsconfig.json",
  "vite.config.ts"
];
const excludedPathFragments = [
  "outputs/artifact_manifest.json",
  "outputs/artifact_manifest.md",
  "outputs/screenshots/"
];
const excludedPathNames = new Set([".DS_Store"]);

async function listFiles(root: string, inputPath: string): Promise<string[]> {
  const absolute = resolve(root, inputPath);
  const info = await stat(absolute);
  if (info.isFile()) {
    return [absolute];
  }

  const children = await readdir(absolute);
  const nested = await Promise.all(children.map((child) => listFiles(root, `${inputPath}/${child}`)));
  return nested.flat();
}

function shouldInclude(root: string, absolutePath: string): boolean {
  const path = relative(root, absolutePath);
  if (path.split("/").some((part) => excludedPathNames.has(part))) {
    return false;
  }
  return !excludedPathFragments.some((fragment) => path.includes(fragment));
}

export async function buildArtifactManifest(root: string): Promise<ArtifactManifest> {
  const files = (await Promise.all(includedRoots.map((entry) => listFiles(root, entry))))
    .flat()
    .filter((filePath) => shouldInclude(root, filePath))
    .sort((a, b) => relative(root, a).localeCompare(relative(root, b)));
  const entries = await Promise.all(
    files.map(async (filePath) => {
      const contents = await readFile(filePath);
      return {
        path: relative(root, filePath),
        sha256: createHash("sha256").update(contents).digest("hex"),
        bytes: contents.byteLength
      };
    })
  );

  return {
    benchmark: "personal-ai-sovereignty-benchmark",
    version: "0.18.0-artifact-manifest",
    generatedAt: new Date("2026-05-23T00:00:00.000Z").toISOString(),
    artifactCount: entries.length,
    entries,
    verificationCommand: "pnpm artifact:verify"
  };
}

export function renderArtifactManifestMarkdown(manifest: ArtifactManifest): string {
  return `# Artifact Manifest

Generated by \`pnpm artifact:manifest\`.

- Artifact count: ${manifest.artifactCount}
- Verification command: \`${manifest.verificationCommand}\`

## Artifacts

| Path | Bytes | SHA-256 |
| --- | ---: | --- |
${manifest.entries
  .map((entry) => `| \`${entry.path}\` | ${entry.bytes} | \`${entry.sha256}\` |`)
  .join("\n")}
`;
}

export async function writeArtifactManifest(root: string): Promise<ArtifactManifest> {
  const manifest = await buildArtifactManifest(root);
  await writeFile(resolve(root, "outputs/artifact_manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  await writeFile(resolve(root, "outputs/artifact_manifest.md"), renderArtifactManifestMarkdown(manifest));
  return manifest;
}

export async function verifyArtifactManifest(root: string): Promise<string[]> {
  const expected = JSON.parse(
    await readFile(resolve(root, "outputs/artifact_manifest.json"), "utf8")
  ) as ArtifactManifest;
  const actual = await buildArtifactManifest(root);
  const actualByPath = new Map(actual.entries.map((entry) => [entry.path, entry]));
  const failures: string[] = [];

  for (const expectedEntry of expected.entries) {
    const actualEntry = actualByPath.get(expectedEntry.path);
    if (!actualEntry) {
      failures.push(`missing ${expectedEntry.path}`);
      continue;
    }
    if (actualEntry.sha256 !== expectedEntry.sha256 || actualEntry.bytes !== expectedEntry.bytes) {
      failures.push(`changed ${expectedEntry.path}`);
    }
  }
  for (const actualEntry of actual.entries) {
    if (!expected.entries.some((entry) => entry.path === actualEntry.path)) {
      failures.push(`untracked ${actualEntry.path}`);
    }
  }

  return failures;
}
