import { runToolAgentScenarios, type ToolAgentScenarioTrace } from "../agent/toolAgent";
import type { Scenario } from "../shared/types";

export interface ToolTraceReport {
  benchmark: string;
  version: string;
  generatedAt: string;
  scenarioCount: number;
  toolCallCount: number;
  executedCount: number;
  blockedCount: number;
  unsafeRawAttemptsBlocked: number;
  policyViolationCount: number;
  traces: ToolAgentScenarioTrace[];
  limitations: string[];
}

export function buildToolTraceReport(scenarios: Scenario[]): ToolTraceReport {
  const traces = runToolAgentScenarios(scenarios);
  const allCalls = traces.flatMap((trace) => trace.calls);
  const unsafeRawAttemptsBlocked = allCalls.filter(
    (call) => call.expected === "must_block" && call.status === "blocked" && call.policyCompliant
  ).length;

  return {
    benchmark: "personal-ai-sovereignty-benchmark",
    version: "0.5.0-tool-trace-scaffold",
    generatedAt: new Date("2026-05-22T00:00:00.000Z").toISOString(),
    scenarioCount: scenarios.length,
    toolCallCount: allCalls.length,
    executedCount: allCalls.filter((call) => call.status === "executed").length,
    blockedCount: allCalls.filter((call) => call.status === "blocked").length,
    unsafeRawAttemptsBlocked,
    policyViolationCount: allCalls.filter((call) => !call.policyCompliant).length,
    traces,
    limitations: [
      "Tool traces execute deterministic in-process tool adapters, not real external business APIs.",
      "The report proves that the benchmark can audit tool-call decisions; it does not prove production egress control.",
      "Consent receipts are simulated tamper-evident records, not legally signed authorization objects."
    ]
  };
}

export function renderToolTraceMarkdown(report: ToolTraceReport): string {
  const scenarioRows = report.traces
    .map(
      (trace) =>
        `| ${trace.scenarioId} | ${trace.toolCallCount} | ${trace.executedCount} | ${trace.blockedCount} | ${trace.policyViolationCount} | ${trace.interpretation} |`
    )
    .join("\n");
  const sampleCalls = report.traces
    .flatMap((trace) => trace.calls)
    .slice(0, 24)
    .map(
      (call) =>
        `| ${call.id} | ${call.toolName} | ${call.targetLayer} | ${call.releaseForm} | ${call.status} | ${call.expected} | ${call.policyCompliant ? "yes" : "no"} |`
    )
    .join("\n");

  return `# Tool-Agent Trace Report

Generated by \`pnpm eval\`.

## Summary

- Scenario count: ${report.scenarioCount}
- Tool-call count: ${report.toolCallCount}
- Executed calls: ${report.executedCount}
- Blocked calls: ${report.blockedCount}
- Unsafe raw attempts blocked: ${report.unsafeRawAttemptsBlocked}
- Policy violations: ${report.policyViolationCount}

## Scenario Trace Summary

| Scenario | Tool Calls | Executed | Blocked | Policy Violations | Interpretation |
| --- | ---: | ---: | ---: | ---: | --- |
${scenarioRows}

## Sample Tool Calls

| Call | Tool | Target Layer | Release Form | Status | Expected | Policy Compliant |
| --- | --- | --- | --- | --- | --- | --- |
${sampleCalls}

## Limitations

${report.limitations.map((limitation) => `- ${limitation}`).join("\n")}
`;
}
