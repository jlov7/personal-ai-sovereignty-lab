import type { Scenario } from "../shared/types";

export function renderScenarioCards(scenarios: Scenario[]): string {
  return `# Scenario Cards

These cards are generated by \`pnpm eval\`. They make each benchmark task reviewable without reading source fixtures.

${scenarios.map(renderScenarioCard).join("\n\n")}
`;
}

function renderScenarioCard(scenario: Scenario): string {
  const dataRows = scenario.dataItems
    .map(
      (item) =>
        `| ${item.id} | ${item.sensitivity} | ${item.defaultBoundary} | ${item.allowedLayers.join(", ")} | ${item.containsPii ? "yes" : "no"} |`
    )
    .join("\n");

  return `## ${scenario.title}

- ID: \`${scenario.id}\`
- Domain: \`${scenario.domain}\`
- Autonomy: \`${scenario.requestedAutonomy}\`
- External interaction: ${scenario.externalInteraction ? "yes" : "no"}
- Boundary crossing required for success: ${scenario.requiresBoundaryCrossingForSuccess ? "yes" : "no"}

### Task

${scenario.task}

### User Objective

${scenario.userObjective}

### Data Items

| ID | Sensitivity | Default Boundary | Allowed Layers | PII |
| --- | --- | --- | --- | --- |
${dataRows}

### Success Criteria

${scenario.successCriteria.map((criterion) => `- ${criterion}`).join("\n")}

### Failure Modes

${scenario.failureModes.map((mode) => `- ${mode}`).join("\n")}
`;
}
